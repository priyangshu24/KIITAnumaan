export interface AnswerFeedback {
  score: number
  tip: string
}

export const evaluateAnswer = (answer: string): AnswerFeedback => {
  const words = answer.trim().split(/\s+/).filter(Boolean).length
  if (words === 0)
    return { score: 0, tip: "You didn't answer — even a rough outline beats silence in a real interview." }
  if (words < 15)
    return {
      score: 2,
      tip: 'Too brief — walk through your reasoning step by step, and mention a tradeoff or a concrete example.',
    }
  if (words < 40)
    return { score: 3, tip: 'Solid start. Add one more layer of depth — an edge case, a tradeoff, or a metric.' }
  return { score: 5, tip: 'Strong, detailed answer. That is the depth interviewers want to see in a real round.' }
}

export const getInterviewHint = (question: string): string => {
  const q = question.toLowerCase()
  if (q.includes('design') || q.includes('lru') || q.includes('rate limiter') || q.includes('parking'))
    return 'Structure it: 1) Clarify requirements & scale, 2) Propose a high-level design, 3) Deep-dive one component, 4) Discuss tradeoffs.'
  if (q.includes('sql'))
    return 'Narrate the query build-up: SELECT → FROM → JOIN → WHERE → GROUP BY. Mention indexing if it is relevant.'
  if (q.includes('why') || q.includes('tell me about yourself') || q.includes('conflict') || q.includes('5 years'))
    return 'Use the STAR method — Situation, Task, Action, Result — and keep it under 90 seconds.'
  if (q.includes('client') || q.includes('revenue') || q.includes('case'))
    return 'Structure with MECE: break the problem into mutually exclusive, collectively exhaustive buckets before diving into one branch.'
  if (q.includes('encryption') || q.includes('attack') || q.includes('risk'))
    return 'Define the term precisely first, then give a concrete real-world example or mitigation.'
  return 'Break your answer into approach, tradeoffs, and a concrete example — interviewers grade the process, not just the final answer.'
}

